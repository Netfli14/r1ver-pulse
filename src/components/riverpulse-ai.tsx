async function readStream(res: Response, onText: (t: string) => void) {
  if (!res.ok || !res.body) throw new Error((await res.text()) || "Ошибка AI");
  const reader = res.body.getReader();
  const dec = new TextDecoder();
  let acc = "";
  for (;;) {
    const { done, value } = await reader.read();
    if (done) break;
    acc += dec.decode(value, { stream: true });
    onText(acc);
  }
}

export function AdminReportAnalysis({ reports }: { reports: DemoReport[] }) {
  const [text, setText] = useState("");
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");
  async function run() {
    setLoading(true); setError(""); setText("");
    try {
      const token = sessionStorage.getItem("riverpulse-admin-session");
      const res = await fetch("/api/ai-reports", {
        method: "POST",
        headers: { "content-type": "application/json", ...(token ? { authorization: "Bearer " + token } : {}) },
        body: JSON.stringify({ reports }),
      });
      await readStream(res, setText);
    } catch (e) { setError(e instanceof Error ? e.message : "Ошибка"); }
    finally { setLoading(false); }
  }
  return (
    <section className="rp-card rp-panel rp-ai-analysis">
      <div className="rp-panel-head">
        <div>
          <h2><AlertTriangle size={20} /> AI-анализ обращений</h2>
          <p>Gemini 2.5 Pro изучает все {reports.length} обращений и показывает, где решение нужно срочно.</p>
        </div>
        <button className="rp-button primary" onClick={run} disabled={loading}>
          {loading ? <RefreshCw className="spin" size={16} /> : <Bot size={16} />}
          {text ? "Обновить анализ" : "Запустить анализ"}
        </button>
      </div>
      {error && <p className="rp-error">{error}</p>}
      {text ? <div className="rp-ai-text">{text}</div> : !loading && <p className="rp-muted">Нажмите «Запустить анализ», чтобы получить сводку.</p>}
      {loading && !text && <p className="rp-muted">Анализирую обращения…</p>}
    </section>
  );
}

type Msg = { role: "user" | "assistant"; content: string };
const suggestions = ["Что такое мутность воды и почему она растёт?", "Можно ли купаться в Есиле?", "Как работают роботы-очистители?", "Что делать, если я увидел мёртвую рыбу?"];

export function LearnChat() {
  const [messages, setMessages] = useState<Msg[]>([]);
  const [input, setInput] = useState("");
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");
  const endRef = useRef<HTMLDivElement>(null);
  async function ask(q: string) {
    const question = q.trim();
    if (!question || loading) return;
    const next: Msg[] = [...messages, { role: "user", content: question }];
    setMessages([...next, { role: "assistant", content: "" }]);
    setInput(""); setLoading(true); setError("");
    try {
      const res = await fetch("/api/ai-learn", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ messages: next }) });
      await readStream(res, (t) => { setMessages([...next, { role: "assistant", content: t }]); endRef.current?.scrollIntoView({ block: "nearest" }); });
    } catch (e) {
      setMessages(next);
      setError(e instanceof Error ? e.message : "Ошибка");
    } finally { setLoading(false); }
  }
  return (
    <section className="rp-card rp-panel rp-learn-chat">
      <div className="rp-chat-head"><Bot size={22} /><div><h2>Спросите RiverPulse AI</h2><p>Работает на Gemini 2.5 Flash · отвечает на вопросы о воде и экологии</p></div></div>
      <div className="rp-chat-log">
        {messages.length === 0 && (
          <div className="rp-chat-suggest">
            {suggestions.map((s) => <button key={s} className="rp-button secondary" onClick={() => ask(s)}>{s}</button>)}
          </div>
        )}
        {messages.map((m, i) => (
          <div key={i} className={"rp-chat-msg " + m.role}>{m.content || (loading ? "…" : "")}</div>
        ))}
        <div ref={endRef} />
      </div>
      {error && <p className="rp-error">{error}</p>}
      <form className="rp-chat-form" onSubmit={(e) => { e.preventDefault(); ask(input); }}>
        <input value={input} onChange={(e) => setInput(e.target.value)} placeholder="Например: что значит pH 8,5?" maxLength={1000} />
        <button className="rp-button primary" disabled={loading || !input.trim()} aria-label="Отправить">
          {loading ? <RefreshCw className="spin" size={16} /> : <Send size={16} />}
        </button>
      </form>
    </section>
  );
}

